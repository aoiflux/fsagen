// upcase is the whole table, character by character.
var upcase = func() []uint16 {
	t := make([]uint16, 1<<16)
	for i := range t {
		t[i] = uint16(i)
	}
	for _, r := range upcaseRuns {
		for c := int(r.first); c <= int(r.last); c += r.step {
			t[c] = uint16(c + r.delta)
		}
	}
	return t
}()

// upcaseBytes is $UpCase's content: the table, little-endian.
func upcaseBytes() []byte {
	b := make([]byte, 2*len(upcase))
	for i, c := range upcase {
		binary.LittleEndian.PutUint16(b[2*i:], c)
	}
	return b
}
